async def generate_home_recommendations(
    planner_input: HomePlannerInput,
    user_id: Optional[int] = None
) -> Tuple[RecommendationSummary, Optional[int]]:
    """Generate budget-aware recommendations for home interior spaces."""
    budget = planner_input.total_budget
    allocations = calculate_home_budget_allocation(budget)
    items: List[RecommendationItem] = []
    is_live_ai = False
    ai_summary = ""

    # Platform adapters seed data based on requested quantities
    # Lighting
    if planner_input.num_lights > 0:
        light_budget = next(a.allocated_amount for a in allocations if a.category == "Lighting")
        amazon_lights = get_amazon_product_recommendations("lighting", light_budget)
        if amazon_lights:
            choice = amazon_lights[0]
            qty = min(planner_input.num_lights, 4)
            items.append(RecommendationItem(
                name=choice["name"],
                category="Lighting",
                description=f"Energy-efficient warm white lighting for {planner_input.room_type}.",
                price=choice["price"],
                quantity=qty,
                total_price=choice["price"] * qty,
                platform="Amazon",
                url=choice["url"],
                reason=choice["reason"],
                rating=choice["rating"],
                review_count=choice["review_count"]
            ))

    # Ceiling Fans
    if planner_input.num_fans > 0:
        fan_budget = next(a.allocated_amount for a in allocations if a.category == "Ceiling Fans")
        fan_picks = get_amazon_product_recommendations("ceiling fans", fan_budget)
        if fan_picks:
            choice = fan_picks[0]
            items.append(RecommendationItem(
                name=choice["name"],
                category="Ceiling Fans",
                description=f"Silent BLDC energy-saving cooling for {planner_input.room_type}.",
                price=choice["price"],
                quantity=planner_input.num_fans,
                total_price=choice["price"] * planner_input.num_fans,
                platform="Amazon",
                url=choice["url"],
                reason=choice["reason"],
                rating=choice["rating"],
                review_count=choice["review_count"]
            ))

    # Furniture
    if planner_input.num_furniture > 0:
        furn_budget = next(a.allocated_amount for a in allocations if a.category == "Furniture")
        ikea_furn = get_ikea_product_recommendations("furniture", furn_budget)
        flipkart_furn = get_flipkart_product_recommendations("furniture", furn_budget)
        
        if ikea_furn:
            choice = ikea_furn[0]
            items.append(RecommendationItem(
                name=choice["name"],
                category="Furniture",
                description=f"Scandinavian functional furniture suited for {planner_input.style_preference} styling.",
                price=choice["price"],
                quantity=1,
                total_price=choice["price"],
                platform="IKEA",
                url=choice["url"],
                reason=choice["reason"],
                rating=choice["rating"],
                review_count=choice["review_count"]
            ))
        if flipkart_furn and planner_input.num_furniture > 1:
            choice = flipkart_furn[0]
            items.append(RecommendationItem(
                name=choice["name"],
                category="Furniture",
                description=f"Engineered durable living unit for {planner_input.room_type}.",
                price=choice["price"],
                quantity=1,
                total_price=choice["price"],
                platform="Flipkart",
                url=choice["url"],
                reason=choice["reason"],
                rating=choice["rating"],
                review_count=choice["review_count"]
            ))

    # Decor
    if planner_input.num_decor > 0:
        decor_budget = next(a.allocated_amount for a in allocations if a.category == "Decor")
        decor_picks = get_ikea_product_recommendations("decor", decor_budget)
        if decor_picks:
            choice = decor_picks[0]
            items.append(RecommendationItem(
                name=choice["name"],
                category="Decor",
                description=f"Aesthetic accent piece complementing {planner_input.style_preference} interior.",
                price=choice["price"],
                quantity=planner_input.num_decor,
                total_price=choice["price"] * planner_input.num_decor,
                platform="IKEA",
                url=choice["url"],
                reason=choice["reason"],
                rating=choice["rating"],
                review_count=choice["review_count"]
            ))

    # Optional Gemini enhancement for rich personalized notes
    if is_ai_available():
        prompt = f"""
Plan interior decor for a {planner_input.room_type} with a budget of INR ₹{budget:,.2f}.
Style: {planner_input.style_preference}.
Provide a brief 2-sentence summary explaining how to maximize this budget without overspending.
"""
        ai_resp = await generate_ai_text_recommendations(prompt)
        if ai_resp and isinstance(ai_resp, dict):
            ai_summary = ai_resp.get("summary", "")
            is_live_ai = True

    if not ai_summary:
        ai_summary = (
            f"Tailored for {planner_input.room_type} with {planner_input.style_preference} aesthetic. "
            f"Balanced across lighting, furniture, cooling, and decor within your ₹{budget:,.2f} budget."
        )

    # Calculate actual spends per category
    total_spend = sum(item.total_price for item in items)
    for alloc in allocations:
        alloc.spent_amount = sum(i.total_price for i in items if i.category.lower() == alloc.category.lower())

    remaining = round(budget - total_spend, 2)
    status_str = evaluate_budget_status(budget, total_spend)

    summary = RecommendationSummary(
        planner_type="home",
        total_budget=budget,
        total_spend=round(total_spend, 2),
        total_travel_estimate=0.0,
        effective_total=round(total_spend, 2),
        remaining_budget=remaining,
        budget_status=status_str,
        allocations=allocations,
        items=items,
        ai_summary=ai_summary,
        is_demo=not is_live_ai
    )

    history_id = None
    if user_id:
        history_id = save_recommendation_history(
            user_id=user_id,
            planner_type="home",
            total_budget=budget,
            input_data=planner_input.model_dump(),
            summary=summary
        )

    return summary, history_id

