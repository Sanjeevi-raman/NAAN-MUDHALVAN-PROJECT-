def save_recommendation_history(
    user_id: int,
    planner_type: str,
    total_budget: float,
    input_data: Dict[str, Any],
    summary: RecommendationSummary
) -> int:
    """Save user planner request and resulting items into the database."""
    conn = get_db_connection()
    cursor = conn.cursor()

    # 1. Save planner request
    cursor.execute("""
        INSERT INTO planner_requests (user_id, planner_type, total_budget, input_data)
        VALUES (?, ?, ?, ?)
    """, (user_id, planner_type, total_budget, json.dumps(input_data)))
    request_id = cursor.lastrowid

    # 2. Save recommendation history
    cursor.execute("""
        INSERT INTO recommendation_histories (
            user_id, planner_request_id, planner_type, total_budget,
            allocated_spend, estimated_travel, remaining_budget, status, summary_text
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        user_id, request_id, planner_type, total_budget,
        summary.total_spend, summary.total_travel_estimate, summary.remaining_budget,
        summary.budget_status, summary.ai_summary or "Plan generated by PocketSmart AI"
    ))
    history_id = cursor.lastrowid

    # 3. Save recommendation items
    for item in summary.items:
        cursor.execute("""
            INSERT INTO recommendation_results (
                history_id, name, category, description, price, quantity,
                total_price, platform, url, reason, distance_km, travel_time_minutes,
                travel_cost_estimate, rating, review_count, location, is_mock
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            history_id, item.name, item.category, item.description,
            item.price, item.quantity, item.total_price, item.platform,
            item.url, item.reason, item.distance_km, item.travel_time_minutes,
            item.travel_cost_estimate, item.rating, item.review_count,
            item.location, 1 if item.is_mock else 0
        ))

    conn.commit()
    conn.close()
    return history_id

