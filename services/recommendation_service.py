async def generate_party_recommendations(
    planner_input: PartyPlannerInput,
    user_id: Optional[int] = None
) -> Tuple[RecommendationSummary, Optional[int]]:
    """
    Generate event budget plan with location-aware nearby venues,
    60km rule evaluation, travel costs, and catering/entertainment.
    """
    budget = planner_input.total_budget
    allocations = calculate_party_budget_allocation(budget, planner_input.accommodation_needed)
    items: List[RecommendationItem] = []
    total_travel_cost = 0.0

    # 1. Nearby venues if location provided
    if planner_input.user_latitude is not None and planner_input.user_longitude is not None:
        venues = await search_nearby_venues(
            user_lat=planner_input.user_latitude,
            user_lon=planner_input.user_longitude,
            event_type=planner_input.event_type,
            guest_count=planner_input.guest_count,
            budget=budget,
            travel_mode=planner_input.travel_mode or "car"
        )
        for v in venues[:3]:  # Top 3 location alternatives
            total_travel_cost = max(total_travel_cost, v["travel_cost_estimate"])
            items.append(RecommendationItem(
                name=v["name"],
                category=v["category"],
                description=v["description"],
                price=v["price"],
                quantity=1,
                total_price=v["price"],
                platform=v["platform"],
                url=v["url"],
                reason=v["reason"],
                distance_km=v["distance_km"],
                travel_time_minutes=v["travel_time_minutes"],
                travel_cost_estimate=v["travel_cost_estimate"],
                effective_total_cost=v["effective_total_cost"],
                rating=v["rating"],
                review_count=v["review_count"],
                location=v["location"],
                google_maps_url=v["google_maps_url"],
                is_nearby=v["is_nearby"]
            ))
    else:
        # Default venue suggestion when location permission denied / not provided
        venue_budget = next(a.allocated_amount for a in allocations if a.category == "Venue")
        items.append(RecommendationItem(
            name=f"Premium {planner_input.venue_preference} & Banquet Space",
            category="Venue",
            description=f"Event hall suitable for {planner_input.guest_count} guests. Location permission required for nearby distance.",
            price=venue_budget * 0.9,
            quantity=1,
            total_price=venue_budget * 0.9,
            platform="Local Venue Partner",
            url=get_google_maps_url(f"{planner_input.venue_preference} banquet hall"),
            reason=f"Standard banquet capacity for {planner_input.guest_count} guests within {planner_input.event_type} budget.",
            rating=4.4,
            review_count=210,
            location="Local City Area"
        ))

    # 2. Catering
    catering_budget = next(a.allocated_amount for a in allocations if a.category == "Catering")
    per_plate = round(catering_budget / max(1, planner_input.guest_count), 2)
    swiggy_url = get_swiggy_search_url(f"party catering {planner_input.catering_preference}")
    zomato_url = get_zomato_search_url(f"catering {planner_input.catering_preference}")
    
    items.append(RecommendationItem(
        name=f"Deluxe {planner_input.catering_preference} Catering Package",
        category="Catering",
        description=f"Multi-course spread with welcome drinks, appetizers, main course buffet, and desserts.",
        price=per_plate,
        quantity=planner_input.guest_count,
        total_price=catering_budget * 0.95,
        platform="Swiggy / Local Caterer",
        url=swiggy_url,
        reason=f"Calculated at ₹{per_plate:,.0f} per plate for {planner_input.guest_count} guests.",
        rating=4.5,
        review_count=340
    ))

    # 3. Decoration
    if planner_input.decoration_needed:
        decor_budget = next(a.allocated_amount for a in allocations if a.category == "Decoration")
        items.append(RecommendationItem(
            name=f"Theme Balloon & Floral Arch Decor ({planner_input.event_type})",
            category="Decoration",
            description="Stage backdrop, entrance arch, customized photo-booth, and ambient lighting.",
            price=decor_budget * 0.9,
            quantity=1,
            total_price=decor_budget * 0.9,
            platform="Local Decor Specialist",
            url=get_amazon_search_url(f"party decoration kit {planner_input.event_type}"),
            reason=f"Specially styled backdrop and lighting for {planner_input.event_type} celebration.",
            rating=4.3,
            review_count=150
        ))

    # 4. Entertainment
    if planner_input.entertainment_needed:
        ent_budget = next(a.allocated_amount for a in allocations if a.category == "Entertainment")
        items.append(RecommendationItem(
            name="Professional Sound System, DJ & Emcee Hosting",
            category="Entertainment",
            description="High-output audio setup, wireless microphones, party lighting effects, and host.",
            price=ent_budget * 0.85,
            quantity=1,
            total_price=ent_budget * 0.85,
            platform="Local Service Provider",
            url=get_google_maps_url("party dj sound system rental"),
            reason="Keeps guests engaged with quality audio and coordinated event games.",
            rating=4.6,
            review_count=98
        ))

    # 5. Accommodation (if requested)
    if planner_input.accommodation_needed:
        accom_budget = next(a.allocated_amount for a in allocations if a.category == "Accommodation")
        items.append(RecommendationItem(
            name="OYO / Partner Hotel Guest Suites (Block of 5 Rooms)",
            category="Accommodation",
            description="Air-conditioned double rooms with complimentary breakfast for out-of-town guests.",
            price=accom_budget * 0.9,
            quantity=1,
            total_price=accom_budget * 0.9,
            platform="OYO",
            url=get_oyo_search_url("party guest rooms"),
            reason="Clean, comfortable overnight stays close to the celebration venue.",
            rating=4.2,
            review_count=450
        ))

    total_spend = sum(item.total_price for item in items)
    effective_total = total_spend + total_travel_cost
    remaining = round(budget - effective_total, 2)
    status_str = evaluate_budget_status(budget, effective_total)

    # Update spent_amounts in allocations
    for alloc in allocations:
        alloc.spent_amount = sum(i.total_price for i in items if i.category.lower() == alloc.category.lower())

    summary = RecommendationSummary(
        planner_type="party",
        total_budget=budget,
        total_spend=round(total_spend, 2),
        total_travel_estimate=round(total_travel_cost, 2),
        effective_total=round(effective_total, 2),
        remaining_budget=remaining,
        budget_status=status_str,
        allocations=allocations,
        items=items,
        ai_summary=(
            f"Curated {planner_input.event_type} package for {planner_input.guest_count} guests. "
            f"Combines venue, catering, and travel estimates within ₹{budget:,.2f} budget."
        ),
        is_demo=False
    )

    history_id = None
    if user_id:
        history_id = save_recommendation_history(
            user_id=user_id,
            planner_type="party",
            total_budget=budget,
            input_data=planner_input.model_dump(),
            summary=summary
        )

    return summary, history_id

